#!/usr/bin/env python3
"""
Simple greeting module for Testing-copilot repository.

This module provides a simple greeting function that returns "hello there".
"""


def greeting():
    """
    Returns a simple greeting message.
    
    Returns:
        str: The greeting message "hello there"
    """
    return "hello there"


def main():
    """
    Main function to demonstrate the greeting functionality.
    """
    print(greeting())


if __name__ == "__main__":
    main()